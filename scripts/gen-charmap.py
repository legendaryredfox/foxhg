#!/usr/bin/env python3
"""Generate core/.../text/CharmapData.kt from a HeartGold charmap.txt (HEXCODE=token per line).

Usage: .venv-free, stdlib only:  python3 -I scripts/gen-charmap.py references/hg-engine/charmap.txt
The character table is a fact about the game's encoding; it is regenerated, not hand-edited.
"""
import sys

src = sys.argv[1]
entries = []
for raw in open(src, encoding="utf-8"):
    line = raw.rstrip("\r\n").lstrip(" \t")
    if not line or line.startswith("//"):
        continue
    code, sep, token = line.partition("=")
    if not sep or len(code) != 4:
        continue
    int(code, 16)
    entries.append((code.upper(), token))

def kt(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")

chunks = []
for i in range(0, len(entries), 150):
    body = "\\n".join(f"{c}={kt(t)}" for c, t in entries[i:i + 150])
    chunks.append(f'    "{body}"')

joined = ",\n".join(chunks)
out = (
    "package io.github.legendaryredfox.foxhg.core.text\n\n"
    f"// GENERATED by scripts/gen-charmap.py from a HeartGold/SoulSilver charmap.txt ({len(entries)} entries). Do not edit.\n"
    "internal val CHARMAP_CHUNKS: List<String> = listOf(\n"
    f"{joined},\n"
    ")\n"
)
dest = "core/src/commonMain/kotlin/io/github/legendaryredfox/foxhg/core/text/CharmapData.kt"
import os
os.makedirs(os.path.dirname(dest), exist_ok=True)
open(dest, "w", encoding="utf-8").write(out)
print(f"wrote {dest}: {len(entries)} entries")
