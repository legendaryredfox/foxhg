#!/usr/bin/env python3
"""Generate core/.../script/ScrcmdData.kt from the HGSS script command database (hgss_v2.json + hgss_scrcmd_database.json).

Usage: python3 -I scripts/gen-scrcmd.py references/scrcmd-database
The command table (opcode, name, parameter kinds) and the movement names are facts about the game, taken from the
MIT-licensed scrcmd-database project; they are regenerated, not hand-edited. Commands whose parameters depend on a
mode value have no fixed parameter list here ("-"); the parser handles them in code.
"""
import json
import sys

root = sys.argv[1]
v2 = json.load(open(f"{root}/hgss_v2.json", encoding="utf-8"))
legacy = json.load(open(f"{root}/hgss_scrcmd_database.json", encoding="utf-8"))

commands = []
for name, cmd in v2["commands"].items():
    if cmd["type"] != "script_cmd":
        continue
    params = cmd.get("params")
    if params is None:
        spec = "-"
    else:
        def clean(n, i):
            n = "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in n).strip("_")
            return n or f"arg{i}"
        spec = ",".join(f"{p['type']}:{clean(p['name'], i)}" for i, p in enumerate(params)) or "."
    commands.append((cmd["id"], name, spec))
commands.sort()
assert len({c[0] for c in commands}) == len(commands)

movements = sorted((int(k, 16), m["name"]) for k, m in legacy["movements"].items())
comparisons = sorted((int(k, 16), n) for k, n in legacy["comparisonOperators"].items())

def kt(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")

def chunks(lines):
    out = []
    for i in range(0, len(lines), 100):
        out.append('    "' + "\\n".join(kt(l) for l in lines[i:i + 100]) + '"')
    return ",\n".join(out)

body = f'''package io.github.romulofer.foxhg.core.script

// GENERATED by scripts/gen-scrcmd.py from the scrcmd-database HGSS files ({len(commands)} commands). Do not edit.
internal val SCRCMD_CHUNKS = listOf(
{chunks([f"{i}|{n}|{s}" for i, n, s in commands])},
)

internal val MOVEMENT_CHUNKS = listOf(
{chunks([f"{i}|{n}" for i, n in movements])},
)

internal val COMPARISON_CHUNKS = listOf(
{chunks([f"{i}|{n}" for i, n in comparisons])},
)
'''
open("core/src/commonMain/kotlin/io/github/romulofer/foxhg/core/script/ScrcmdData.kt", "w", encoding="utf-8").write(body)
print(len(commands), len(movements), len(comparisons))
