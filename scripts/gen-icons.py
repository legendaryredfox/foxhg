#!/usr/bin/env python3
"""Generate core/.../graphics/IconData.kt from the pokeheartgold decomp.

Usage: python3 -I scripts/gen-icons.py references/pokeheartgold
Two tables that say which graphics file belongs to what, and are facts about the game: the item icon files of every
item (src/item.c, `sItemNarcIds`) and the palette of every Pokémon icon (src/pokemon_icon_idx.c). Regenerated, not hand-edited.
"""
import re
import sys

root = sys.argv[1]
items_h = open(f"{root}/include/constants/items.h", encoding="utf-8").read()
item_c = open(f"{root}/src/item.c", encoding="utf-8").read()
icon_c = open(f"{root}/src/pokemon_icon_idx.c", encoding="utf-8").read()

ids = {m.group(1): int(m.group(2)) for m in re.finditer(r"#define\s+(ITEM_\w+)\s+(\d+)\b", items_h)}
table = re.search(r"sItemNarcIds\[ITEMS_COUNT\]\[4\] = \{(.*?)\n\};", item_c, re.S).group(1)
rows = []
for m in re.finditer(r"\[(ITEM_\w+)\]\s*=\s*\{[^,]*,\s*NARC_item_icon_item_icon_(\d+)_NCGR,\s*NARC_item_icon_item_icon_(\d+)_NCLR", table):
    name = m.group(1)
    if name in ids:
        rows.append((ids[name], int(m.group(2)), int(m.group(3))))
rows.sort()

pal = re.search(r"sPokemonPalNoBySpeciesAndForm\[\] = \{(.*?)\};", icon_c, re.S).group(1)
palettes = [int(x) for x in re.findall(r"\d+", pal)]

sep = chr(92) + "n"
item_text = sep.join(f"{i}|{g}|{c}" for i, g, c in rows)
out = f'''package io.github.romulofer.foxhg.core.graphics

// GENERATED by scripts/gen-icons.py from the pokeheartgold decomp. Do not edit.
// Item icons: `item|ncgr file|nclr file` (indexes into a/0/1/8). Pokémon icon palettes: one number per icon slot (species, then forms).
internal const val ITEM_ICON_DATA = "{item_text}"

internal const val POKEMON_ICON_PALETTES = "{",".join(map(str, palettes))}"
'''
open("core/src/commonMain/kotlin/io/github/romulofer/foxhg/core/graphics/IconData.kt", "w", encoding="utf-8").write(out)
print(len(rows), "item icons;", len(palettes), "pokemon palette entries")
