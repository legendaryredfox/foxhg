#!/usr/bin/env python3
"""Generate core/.../data/map/TileTypeData.kt from the pokeheartgold decomp (TILE_BEHAVIOR enum and its flags table).

Usage: python3 -I scripts/gen-tiletypes.py references/pokeheartgold
The names of the tile type byte of the map permissions are facts about the game; they are regenerated, not hand-edited.
"""
import re
import sys

root = sys.argv[1]
header = open(f"{root}/include/constants/metatile_behavior.h", encoding="utf-8").read()
source = open(f"{root}/src/metatile_behavior.c", encoding="utf-8").read()

body = re.search(r"enum TILE_BEHAVIOR \{(.*?)\};", header, re.S).group(1)
names = {}
value = 0
for raw in body.split(","):
    entry = raw.strip()
    if not entry:
        continue
    m = re.match(r"TILE_BEHAVIOR_(\w+)(?:\s*=\s*(\d+))?", entry)
    name, explicit = m.group(1), m.group(2)
    if explicit is not None:
        value = int(explicit)
    names[value] = name
    value += 1

flag_values = {"TILE_BEHAVIOR_FLAG_NONE": 0, "TILE_BEHAVIOR_FLAG_SURFABLE": 1, "TILE_BEHAVIOR_FLAG_ENCOUNTER": 2, "TILE_BEHAVIOR_FLAG_SURFABLE_ENCOUNTER": 3}
flags = {}
for m in re.finditer(r"\[TILE_BEHAVIOR_(\w+)\]\s*=\s*(TILE_BEHAVIOR_FLAG_\w+)", source):
    flags[m.group(1)] = flag_values[m.group(2)]

lines = []
for v in sorted(names):
    if v == 255:
        continue
    n = names[v]
    label = "" if n.isdigit() else n
    lines.append(f"{v}|{label}|{flags.get(n, 0)}")
out = '''package io.github.legendaryredfox.foxhg.core.data.map

// GENERATED by scripts/gen-tiletypes.py from the pokeheartgold decomp (TILE_BEHAVIOR). Do not edit.
// Lines are `type|NAME|flags` (flags: 1 surfable, 2 wild encounters); an empty name means the decomp has none.
internal const val TILE_TYPE_DATA = "''' + "\\n".join(lines) + '"\n'
open("core/src/commonMain/kotlin/io/github/legendaryredfox/foxhg/core/data/map/TileTypeData.kt", "w", encoding="utf-8").write(out)
print(len(lines), "tile types")
